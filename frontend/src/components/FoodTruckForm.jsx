import React, { useState } from 'react';

const COMMON_CUISINES = [
  'Mexican',
  'Italian',
  'American',
  'Asian Fusion',
  'Indian Street Food',
  'BBQ & Grill',
  'Mediterranean',
  'Dessert & Bakery',
  'Seafood',
  'Burgers & Fries'
];

function FoodTruckForm({ onTruckAdded, onCancel }) {
  const [formData, setFormData] = useState({
    truckName: '',
    cuisine: '',
    dailySales: '',
    operating: true,
  });

  const [errors, setErrors] = useState({});
  const [touched, setTouched] = useState({});
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [serverError, setServerError] = useState(null);

  // Validation function
  const validate = (data) => {
    const errs = {};

    // Truck Name
    if (!data.truckName || data.truckName.trim() === '') {
      errs.truckName = 'Truck name is required.';
    } else if (data.truckName.trim().length < 2) {
      errs.truckName = 'Truck name must be at least 2 characters.';
    } else if (data.truckName.trim().length > 100) {
      errs.truckName = 'Truck name cannot exceed 100 characters.';
    }

    // Cuisine
    if (!data.cuisine || data.cuisine.trim() === '') {
      errs.cuisine = 'Cuisine type is required.';
    } else if (data.cuisine.trim().length < 2) {
      errs.cuisine = 'Cuisine must be at least 2 characters.';
    } else if (data.cuisine.trim().length > 50) {
      errs.cuisine = 'Cuisine cannot exceed 50 characters.';
    }

    // Daily Sales
    if (data.dailySales === '' || data.dailySales === null || data.dailySales === undefined) {
      errs.dailySales = 'Daily sales amount is required.';
    } else {
      const numSales = Number(data.dailySales);
      if (isNaN(numSales)) {
        errs.dailySales = 'Daily sales must be a valid numerical value.';
      } else if (numSales < 0) {
        errs.dailySales = 'Daily sales cannot be negative.';
      } else if (numSales > 10000000) {
        errs.dailySales = 'Daily sales cannot exceed $10,000,000.';
      }
    }

    return errs;
  };

  const handleChange = (e) => {
    const { name, value, type, checked } = e.target;
    const val = type === 'checkbox' ? checked : value;

    const nextForm = { ...formData, [name]: val };
    setFormData(nextForm);

    if (touched[name]) {
      const validationErrors = validate(nextForm);
      setErrors(validationErrors);
    }
  };

  const handleBlur = (e) => {
    const { name } = e.target;
    setTouched({ ...touched, [name]: true });
    setErrors(validate(formData));
  };

  const handleCuisineSelect = (c) => {
    const nextForm = { ...formData, cuisine: c };
    setFormData(nextForm);
    setTouched({ ...touched, cuisine: true });
    setErrors(validate(nextForm));
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    setServerError(null);

    // Mark all as touched
    setTouched({
      truckName: true,
      cuisine: true,
      dailySales: true,
    });

    const validationErrors = validate(formData);
    setErrors(validationErrors);

    if (Object.keys(validationErrors).length > 0) {
      return;
    }

    setIsSubmitting(true);
    try {
      await onTruckAdded(formData);
      // Reset form on success
      setFormData({
        truckName: '',
        cuisine: '',
        dailySales: '',
        operating: true,
      });
      setTouched({});
      setErrors({});
    } catch (err) {
      setServerError(err);
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <div className="glass-panel p-4 p-md-5 animate-fade-in mb-5" style={{ maxWidth: '820px', margin: '0 auto' }}>
      {/* Header */}
      <div className="d-flex align-items-center justify-content-between pb-3 mb-4 border-bottom border-secondary border-opacity-25">
        <div>
          <div className="d-flex align-items-center gap-2">
            <span className="fs-3">🚚</span>
            <h2 className="brand-font fw-bold text-white mb-0">Register New Food Truck</h2>
          </div>
          <p className="text-secondary small mb-0 mt-1">
            Fill in the details below. Note: System ID is automatically generated by the PostgreSQL database.
          </p>
        </div>
        {onCancel && (
          <button
            type="button"
            className="btn btn-sm btn-outline-custom"
            onClick={onCancel}
            title="Return to fleet view"
          >
            <i className="bi bi-x-lg me-1"></i> Close
          </button>
        )}
      </div>

      {/* Notice Banner */}
      <div className="alert alert-dark border border-secondary border-opacity-25 d-flex align-items-center gap-3 p-3 rounded-3 mb-4" style={{ background: 'rgba(30, 41, 59, 0.4)' }}>
        <i className="bi bi-shield-check text-warning fs-4"></i>
        <div className="small text-secondary">
          <strong className="text-white">Auto-Increment ID Protected:</strong> Users do not enter an ID. The backend entity assigns a unique identity value upon submission.
        </div>
      </div>

      {/* Server Error Alert */}
      {serverError && (
        <div className="alert alert-danger d-flex flex-column gap-1 p-3 rounded-3 mb-4" role="alert">
          <div className="d-flex align-items-center gap-2 fw-semibold">
            <i className="bi bi-exclamation-triangle-fill"></i>
            <span>Submission Failed: {serverError.message}</span>
          </div>
          {serverError.fieldErrors && (
            <ul className="mb-0 mt-1 ps-3 small">
              {Object.entries(serverError.fieldErrors).map(([field, msg]) => (
                <li key={field}>
                  <strong>{field}:</strong> {msg}
                </li>
              ))}
            </ul>
          )}
        </div>
      )}

      {/* Form */}
      <form onSubmit={handleSubmit} noValidate id="add-food-truck-form">
        <div className="row g-4">
          {/* Truck Name */}
          <div className="col-12 col-md-6">
            <label htmlFor="input-truck-name" className="form-label text-white fw-semibold small">
              Food Truck Name <span className="text-danger">*</span>
            </label>
            <div className="input-group">
              <span className="input-group-text bg-dark border-secondary border-opacity-25 text-secondary">
                <i className="bi bi-shop"></i>
              </span>
              <input
                type="text"
                id="input-truck-name"
                name="truckName"
                value={formData.truckName}
                onChange={handleChange}
                onBlur={handleBlur}
                className={`form-control custom-form-control ${
                  touched.truckName
                    ? errors.truckName
                      ? 'is-invalid'
                      : 'is-valid'
                    : ''
                }`}
                placeholder="e.g. Rolling Tacos & Burritos"
                disabled={isSubmitting}
                required
              />
              {touched.truckName && errors.truckName && (
                <div className="invalid-feedback d-block text-danger small mt-1">
                  <i className="bi bi-exclamation-circle me-1"></i>
                  {errors.truckName}
                </div>
              )}
            </div>
            <div className="form-text text-secondary small">
              Must be 2–100 characters long.
            </div>
          </div>

          {/* Daily Sales */}
          <div className="col-12 col-md-6">
            <label htmlFor="input-daily-sales" className="form-label text-white fw-semibold small">
              Estimated Daily Sales ($ USD) <span className="text-danger">*</span>
            </label>
            <div className="input-group">
              <span className="input-group-text bg-dark border-secondary border-opacity-25 text-warning fw-bold">
                $
              </span>
              <input
                type="number"
                step="0.01"
                min="0"
                id="input-daily-sales"
                name="dailySales"
                value={formData.dailySales}
                onChange={handleChange}
                onBlur={handleBlur}
                className={`form-control custom-form-control ${
                  touched.dailySales
                    ? errors.dailySales
                      ? 'is-invalid'
                      : 'is-valid'
                    : ''
                }`}
                placeholder="e.g. 1450.75"
                disabled={isSubmitting}
                required
              />
              {touched.dailySales && errors.dailySales && (
                <div className="invalid-feedback d-block text-danger small mt-1">
                  <i className="bi bi-exclamation-circle me-1"></i>
                  {errors.dailySales}
                </div>
              )}
            </div>
            <div className="form-text text-secondary small">
              Enter non-negative value (e.g., 500 or 1200.50).
            </div>
          </div>

          {/* Cuisine */}
          <div className="col-12">
            <label htmlFor="input-cuisine" className="form-label text-white fw-semibold small">
              Cuisine Type <span className="text-danger">*</span>
            </label>
            <div className="input-group">
              <span className="input-group-text bg-dark border-secondary border-opacity-25 text-secondary">
                <i className="bi bi-egg-fried"></i>
              </span>
              <input
                type="text"
                id="input-cuisine"
                name="cuisine"
                value={formData.cuisine}
                onChange={handleChange}
                onBlur={handleBlur}
                className={`form-control custom-form-control ${
                  touched.cuisine
                    ? errors.cuisine
                      ? 'is-invalid'
                      : 'is-valid'
                    : ''
                }`}
                placeholder="Select from below or type custom (e.g., Mexican, Korean BBQ)"
                disabled={isSubmitting}
                required
              />
              {touched.cuisine && errors.cuisine && (
                <div className="invalid-feedback d-block text-danger small mt-1">
                  <i className="bi bi-exclamation-circle me-1"></i>
                  {errors.cuisine}
                </div>
              )}
            </div>

            {/* Quick Cuisine Chips */}
            <div className="d-flex flex-wrap gap-2 mt-2">
              <span className="text-secondary small me-1 align-self-center">Suggested:</span>
              {COMMON_CUISINES.map((c) => (
                <button
                  key={c}
                  type="button"
                  className={`btn btn-sm py-1 px-2 rounded-pill ${
                    formData.cuisine === c
                      ? 'btn-warning text-dark fw-bold'
                      : 'btn-outline-custom text-secondary'
                  }`}
                  style={{ fontSize: '0.75rem' }}
                  onClick={() => handleCuisineSelect(c)}
                  disabled={isSubmitting}
                >
                  {c}
                </button>
              ))}
            </div>
          </div>

          {/* Operating Status Toggle */}
          <div className="col-12">
            <div className="glass-panel p-3 rounded-3 d-flex align-items-center justify-content-between">
              <div className="d-flex align-items-center gap-3">
                <div
                  style={{
                    width: '40px',
                    height: '40px',
                    borderRadius: '10px',
                    background: formData.operating ? 'rgba(16, 185, 129, 0.15)' : 'rgba(239, 68, 68, 0.15)',
                    color: formData.operating ? '#10b981' : '#ef4444',
                    display: 'flex',
                    alignItems: 'center',
                    justifyContent: 'center',
                    fontSize: '1.25rem'
                  }}
                >
                  <i className={`bi ${formData.operating ? 'bi-broadcast-pin' : 'bi-power'}`}></i>
                </div>
                <div>
                  <h6 className="text-white mb-0 fw-semibold">Operating Status</h6>
                  <small className="text-secondary">
                    {formData.operating
                      ? 'Currently open and accepting customer orders'
                      : 'Truck is currently off-duty or in maintenance'}
                  </small>
                </div>
              </div>

              <div className="form-check form-switch fs-4 mb-0">
                <input
                  className="form-check-input"
                  type="checkbox"
                  role="switch"
                  id="toggle-operating-status"
                  name="operating"
                  checked={formData.operating}
                  onChange={handleChange}
                  disabled={isSubmitting}
                  style={{ cursor: 'pointer' }}
                />
              </div>
            </div>
          </div>

          {/* Form Actions */}
          <div className="col-12 d-flex justify-content-end gap-3 mt-4 pt-3 border-top border-secondary border-opacity-25">
            <button
              type="button"
              className="btn btn-outline-custom"
              onClick={() => {
                setFormData({
                  truckName: '',
                  cuisine: '',
                  dailySales: '',
                  operating: true,
                });
                setTouched({});
                setErrors({});
                setServerError(null);
              }}
              disabled={isSubmitting}
            >
              <i className="bi bi-arrow-counterclockwise me-1"></i> Reset
            </button>

            <button
              type="submit"
              id="btn-submit-truck"
              className="btn btn-accent px-4 d-flex align-items-center gap-2"
              disabled={isSubmitting}
            >
              {isSubmitting ? (
                <>
                  <span className="spinner-border spinner-border-sm" role="status" aria-hidden="true"></span>
                  <span>Saving to Database...</span>
                </>
              ) : (
                <>
                  <i className="bi bi-cloud-arrow-up-fill"></i>
                  <span>Add Food Truck</span>
                </>
              )}
            </button>
          </div>
        </div>
      </form>
    </div>
  );
}

export default FoodTruckForm;
