package com.klef.soa.docker.service.impl;

import java.util.List;
import java.util.Optional;
import java.util.stream.Collectors;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import com.klef.soa.docker.dto.FoodTruckRequestDTO;
import com.klef.soa.docker.dto.FoodTruckResponseDTO;
import com.klef.soa.docker.entity.FoodTruckEntity;
import com.klef.soa.docker.repository.FoodTruckRepository;
import com.klef.soa.docker.service.FoodTruckService;

@Service
@Transactional
public class FoodTruckServiceImpl implements FoodTruckService {

    @Autowired
    private FoodTruckRepository foodTruckRepository;

    @Override
    public FoodTruckResponseDTO addFoodTruck(FoodTruckRequestDTO requestDTO) {
        FoodTruckEntity entity = FoodTruckEntity.builder()
                .truckName(requestDTO.getTruckName().trim())
                .cuisine(requestDTO.getCuisine().trim())
                .dailySales(requestDTO.getDailySales())
                .operating(requestDTO.getOperating())
                .build();
        // ID is strictly generated by database
        entity.setId(null);
        FoodTruckEntity saved = foodTruckRepository.save(entity);
        return mapToResponse(saved);
    }

    @Override
    public FoodTruckEntity addFoodTruck(FoodTruckEntity foodTruck) {
        foodTruck.setId(null);
        return foodTruckRepository.save(foodTruck);
    }

    @Override
    @Transactional(readOnly = true)
    public List<FoodTruckResponseDTO> getAllFoodTrucks() {
        return foodTruckRepository.findAll()
                .stream()
                .map(this::mapToResponse)
                .collect(Collectors.toList());
    }

    @Override
    @Transactional(readOnly = true)
    public Optional<FoodTruckResponseDTO> getFoodTruckById(Long id) {
        return foodTruckRepository.findById(id).map(this::mapToResponse);
    }

    @Override
    public FoodTruckResponseDTO updateFoodTruck(Long id, FoodTruckRequestDTO requestDTO) {
        return foodTruckRepository.findById(id).map(existing -> {
            existing.setTruckName(requestDTO.getTruckName().trim());
            existing.setCuisine(requestDTO.getCuisine().trim());
            existing.setDailySales(requestDTO.getDailySales());
            existing.setOperating(requestDTO.getOperating());
            FoodTruckEntity updated = foodTruckRepository.save(existing);
            return mapToResponse(updated);
        }).orElse(null);
    }

    @Override
    public boolean deleteFoodTruck(Long id) {
        if (foodTruckRepository.existsById(id)) {
            foodTruckRepository.deleteById(id);
            return true;
        }
        return false;
    }

    private FoodTruckResponseDTO mapToResponse(FoodTruckEntity entity) {
        return FoodTruckResponseDTO.builder()
                .id(entity.getId())
                .truckName(entity.getTruckName())
                .cuisine(entity.getCuisine())
                .dailySales(entity.getDailySales())
                .operating(entity.getOperating())
                .build();
    }
}
