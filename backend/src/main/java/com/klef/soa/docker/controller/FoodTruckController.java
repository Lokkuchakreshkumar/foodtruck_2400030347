package com.klef.soa.docker.controller;

import java.util.List;
import java.util.Optional;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.CrossOrigin;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RestController;

import com.klef.soa.docker.dto.FoodTruckRequestDTO;
import com.klef.soa.docker.dto.FoodTruckResponseDTO;
import com.klef.soa.docker.service.FoodTruckService;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;

@RestController
@CrossOrigin(origins = "*")
@Tag(name = "Food Truck Management Controller", description = "Endpoints for managing food truck operations")
public class FoodTruckController {

    @Autowired
    private FoodTruckService foodTruckService;

    @GetMapping("/")
    @Operation(summary = "Service Health Check", description = "Checks whether the CRUD service is up and running.")
    public ResponseEntity<String> checkRunning() {
        return ResponseEntity.ok("FoodTruck CRUD Service is running (com.klef.soa.docker)");
    }

    @PostMapping("/add")
    @Operation(summary = "Add New Food Truck", description = "Creates a new food truck record. Note: ID is auto-generated by the database and must not be provided.")
    @ApiResponses(value = {
            @ApiResponse(responseCode = "201", description = "Food Truck created successfully"),
            @ApiResponse(responseCode = "400", description = "Invalid request payload or validation errors")
    })
    public ResponseEntity<FoodTruckResponseDTO> addFoodTruck(
            @Valid @RequestBody FoodTruckRequestDTO requestDTO) {
        FoodTruckResponseDTO saved = foodTruckService.addFoodTruck(requestDTO);
        return new ResponseEntity<>(saved, HttpStatus.CREATED);
    }

    @GetMapping("/displayall")
    @Operation(summary = "Display All Food Trucks", description = "Retrieves all food truck records from the database.")
    @ApiResponse(responseCode = "200", description = "List of food trucks retrieved successfully")
    public ResponseEntity<List<FoodTruckResponseDTO>> displayAll() {
        List<FoodTruckResponseDTO> list = foodTruckService.getAllFoodTrucks();
        return ResponseEntity.ok(list);
    }

    @GetMapping("/get/{id}")
    @Operation(summary = "Get Food Truck By ID", description = "Retrieves a single food truck by its unique ID.")
    @ApiResponses(value = {
            @ApiResponse(responseCode = "200", description = "Food Truck found"),
            @ApiResponse(responseCode = "404", description = "Food Truck not found")
    })
    public ResponseEntity<?> getFoodTruckById(
            @Parameter(description = "ID of the food truck to retrieve") @PathVariable("id") Long id) {
        Optional<FoodTruckResponseDTO> found = foodTruckService.getFoodTruckById(id);
        if (found.isPresent()) {
            return ResponseEntity.ok(found.get());
        } else {
            return ResponseEntity.status(HttpStatus.NOT_FOUND)
                    .body("FoodTruck with ID " + id + " does not exist");
        }
    }

    @PutMapping("/update/{id}")
    @Operation(summary = "Update Food Truck", description = "Updates an existing food truck's details by ID.")
    @ApiResponses(value = {
            @ApiResponse(responseCode = "200", description = "Food Truck updated successfully"),
            @ApiResponse(responseCode = "400", description = "Validation failed"),
            @ApiResponse(responseCode = "404", description = "Food Truck not found")
    })
    public ResponseEntity<?> updateFoodTruck(
            @Parameter(description = "ID of the food truck to update") @PathVariable("id") Long id,
            @Valid @RequestBody FoodTruckRequestDTO requestDTO) {
        FoodTruckResponseDTO updated = foodTruckService.updateFoodTruck(id, requestDTO);
        if (updated != null) {
            return ResponseEntity.ok(updated);
        } else {
            return ResponseEntity.status(HttpStatus.NOT_FOUND)
                    .body("FoodTruck with ID " + id + " does not exist");
        }
    }

    @DeleteMapping("/delete/{id}")
    @Operation(summary = "Delete Food Truck", description = "Deletes a food truck record by its ID.")
    @ApiResponses(value = {
            @ApiResponse(responseCode = "200", description = "Food Truck deleted successfully"),
            @ApiResponse(responseCode = "404", description = "Food Truck does not exist")
    })
    public ResponseEntity<String> deleteFoodTruck(
            @Parameter(description = "ID of the food truck to delete") @PathVariable("id") Long id) {
        boolean deleted = foodTruckService.deleteFoodTruck(id);
        if (deleted) {
            return ResponseEntity.ok("FoodTruck with ID " + id + " deleted successfully");
        } else {
            return ResponseEntity.status(HttpStatus.NOT_FOUND)
                    .body("FoodTruck with ID " + id + " does not exist");
        }
    }
}
